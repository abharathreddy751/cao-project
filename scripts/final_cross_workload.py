"""Final study: one markdown digest of RESULTS_TABLE_FINAL.csv across the six workloads (read-only on the table, exclusive write of the digest).

  python scripts/final_cross_workload.py RESULTS_TABLE_FINAL.csv <out.md>

Per workload and configuration: end-to-end makespan (geometric mean, s) of every policy, and the paired effect (%, 95% CI) of each dynamic
policy against the best-named static baseline HEFT_param_model and against B4 (negative = faster). Nothing is recomputed: the values are the
ones written by scripts/final_analyze.py.
"""
from __future__ import annotations

import csv
import sys

WL = ["h16_l120", "uniform", "h04_l120", "h40_l120", "h16_l40", "h16_l15"]
CFG = ["cpu", "gpu", "ext"]
DYN = ["B4", "B4_param_first", "PRED_RANK_GREEDY", "PRED_RANK_GREEDY_E2E"]
STA = ["HEFT_param_model", "PEFT_param_model", "HEFT_E2E", "HEFT_ORACLE_REF"]


def f(x, nd=2):
    return "" if x in ("", None) else f"{float(x):.{nd}f}"


def eff(r, tag):
    e, lo, hi = r.get(f"vs_{tag}_effect_pct", ""), r.get(f"vs_{tag}_ci_lo_pct", ""), r.get(f"vs_{tag}_ci_hi_pct", "")
    return "-" if e == "" else f"{float(e):+.1f}% [{float(lo):+.1f}, {float(hi):+.1f}]"


def main(src: str, out: str) -> int:
    rows = [r for r in csv.DictReader(open(src, newline="", encoding="utf-8")) if r["kind"] != "confirmatory"]
    by = {(r["workload"], r["config"], r["policy"]): r for r in rows}
    lines = ["# Cross-workload digest (generated by scripts/final_cross_workload.py from RESULTS_TABLE_FINAL.csv)", "",
             "Metric: end-to-end makespan, geometric mean over included blocks, seconds. Effects: paired log-ratio, 95% bootstrap CI, negative = faster than the reference. "
             "The warm-up block is excluded.", ""]
    for wl in WL:
        lines += [f"## {wl}", ""]
        for cfg in CFG:
            lines += [f"### {wl} / {cfg}", "", "| policy | kind | e2e s | vs HEFT_param_model | vs B4 | tasks CPU/GPU | GPU busy |", "|---|---|---|---|---|---|---|"]
            for kind, names in (("dynamic", DYN), ("static", STA)):
                for p in names:
                    r = by.get((wl, cfg, p))
                    if r:
                        lines.append(f"| {p} | {kind} | {f(r['e2e_geo_mean_s'], 3)} | {eff(r, 'static')} | {eff(r, 'B4')} | "
                                     f"{f(r['tasks_cpu'], 0)}/{f(r['tasks_gpu'], 0)} | {f(r['gpu_busy_frac'])} |")
            lines.append("")
    with open(out, "x", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote", out, len(lines), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
