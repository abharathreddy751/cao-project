"""Final study, Phase F: is a B4/PRED hybrid selector justified? (protocol section 10, descriptive; no new runs)

  python scripts/final_hybrid_check.py RESULTS_TABLE_FINAL.csv workload_features.csv <out.md>

For every (workload, config) cell the ceiling of any B4-or-PRED_RANK_GREEDY selector is the oracle best-of-two: min(B4, PRED) makespan. The
headroom of PRED over that ceiling is how much a selector could gain at most (a real selector gains less). The protocol's margin is +-2%:
a hybrid is only worth building if the headroom clearly exceeds it in the development cells. The pre-execution features of each workload
(mean over its instances) are listed next to the PRED-vs-B4 effect so a reader can see whether any feature would separate the cells.
"""
from __future__ import annotations

import csv
import statistics
import sys
from collections import defaultdict


def main(table: str, feats: str, out: str) -> int:
    rows = [r for r in csv.DictReader(open(table, newline="", encoding="utf-8")) if r["kind"] != "confirmatory"]
    g = {(r["workload"], r["config"], r["policy"]): float(r["e2e_geo_mean_s"]) for r in rows}
    ff = defaultdict(list)
    for r in csv.DictReader(open(feats, newline="", encoding="utf-8")):
        ff[r["workload"]].append(r)
    cells = sorted({(w, c) for (w, c, _p) in g})
    L = ["# Hybrid check (generated by scripts/final_hybrid_check.py)", "",
         "headroom = PRED / min(B4, PRED) - 1: the most a B4-or-PRED selector could gain over always using PRED_RANK_GREEDY (oracle ceiling, not reachable at runtime).", "",
         "| workload | config | B4 s | PRED s | PRED vs B4 | oracle best-of-two s | headroom of PRED | n_heavy | cv_chain_cost | tail_ratio |", "|---|---|---|---|---|---|---|---|---|---|"]
    head = []
    for w, c in cells:
        b4, pr = g[(w, c, "B4")], g[(w, c, "PRED_RANK_GREEDY")]
        best = min(b4, pr)
        hd = (pr / best - 1) * 100
        head.append(hd)
        fs = ff[w]

        def m(k):
            return statistics.mean(float(x[k]) for x in fs)

        L.append(f"| {w} | {c} | {b4:.3f} | {pr:.3f} | {(pr / b4 - 1) * 100:+.1f}% | {best:.3f} | {hd:.1f}% | {m('n_heavy'):.0f} | {m('cv_chain_cost'):.2f} | {m('tail_ratio'):.2f} |")
    L += ["", f"cells: {len(cells)}; max headroom {max(head):.1f}%; mean headroom {statistics.mean(head):.2f}%; cells above the 2% margin: {sum(h > 2.0 for h in head)}.", "",
          "Reading rule (protocol section 10): the hybrid is justified only if headroom exceeds the +-2% margin in the development cells and a pre-execution feature separates them."]
    with open(out, "x", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L[-4:-2]))
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
